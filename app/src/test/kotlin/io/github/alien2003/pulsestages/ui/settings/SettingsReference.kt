/**
 * Renders docs/settings-reference.md from the code, one table per group of the Settings screen ([SettingsCatalog]):
 *
 * - the labels, hints, units and option labels of the catalog, resolved with [resources] (English);
 * - the defaults of [AppSettings] (and so of `AlgoParams` and `NapModeParams`) as [SettingsJson.export] writes them;
 * - the accepted values, found by probing [SettingsValidator] and [AlgoParamsValidator] (the two validators of
 *   [SettingsChecks]) with values far outside any range, and reading the constraints they report;
 * - whether a change of the value changes the params hash: [ParamsHasher.hash] of the algorithm parameters with
 *   [OutputOptions.hashExtra] (the output options and the input selection), as the pipeline computes it, before and
 *   after the change.
 *
 * [algorithmMarkdown] is ALGORITHM.md, read for the links to its sections: a heading that no longer exists fails.
 */
internal class SettingsReference(
    private val resources: Resources,
    algorithmMarkdown: String,
) {
    private val defaults = AppSettings()
    private val defaultJson: JsonElement = encode(defaults)
    private val defaultHash: String = paramsHash(defaults)
    private val algorithmAnchors: List<String> = headingAnchors(algorithmMarkdown)

    /**
     * The defaults with every choice switched to another option (e.g. another epoch length) and every empty decimal nap
     * override set to the night's value: a bound that differs on this base depends on another setting, a relation that
     * differs names the override that replaces the night's value when it is set. The nap context margin
     * ([OptionalIntSpec]) stays empty: it replaces no night value in a relation, its own bound is the night's margin.
     */
    private val alternative: AppSettings =
        SettingsCatalog.specsByPath.values
            .distinct()
            .fold(defaults) { s, spec ->
                when (spec) {
                    is ChoiceSpec -> spec.write(s, spec.options.first { it.key != spec.read(s) }.key)
                    is OptionalDoubleSpec -> if (spec.read(s) == null) spec.write(s, spec.inherited(s)) else s
                    else -> s
                }
            }.also { check(SettingsChecks.validate(it).isEmpty()) { "the alternative base is invalid: ${SettingsChecks.validate(it)}" } }

    /** The rows of every group: the keys of every value the reference documents. */
    fun keys(): Set<String> =
        SettingsCatalog.sections
            .flatMap { rows(it) }
            .flatMap { it.keys }
            .toSet()

    /** Whether the reference marks the value at [key] as part of the params hash (null for an unknown key). */
    fun inParamsHash(key: String): Boolean? =
        SettingsCatalog.sections
            .flatMap { rows(it) }
            .firstOrNull { key in it.keys }
            ?.inParamsHash

    /** The whole Markdown file. */
    fun render(): String =
        buildString {
            appendHeader()
            SettingsCatalog.sections.forEach { appendSection(it) }
        }.trimEnd() + "\n"

    // ------------------------------------------------------------------------------------------------ document

    private fun StringBuilder.appendHeader() {
        appendLine(
            "<!-- Generated by SettingsReferenceTest (app/src/test/kotlin/io/github/alien2003/pulsestages/ui/settings/) " +
                "from the code. Do not edit by hand; regenerate with:",
        )
        appendLine("     $REGENERATE -->")
        appendLine()
        appendLine("# Settings reference")
        appendLine()
        appendParagraph(
            "Every setting of the **${text(R.string.settings_title)}** tab, in the groups and the order of the screen, with " +
                "the labels and hints the app shows in English (the app also ships a Russian translation). The tables " +
                "are generated from the code: labels, hints and units from the catalog of the Settings screen, defaults " +
                "from `AppSettings` and `AlgoParams` (including `NapModeParams`), allowed values from the validators " +
                "that guard the settings store and the import, and the last column from the params hash. A unit test " +
                "fails when this file no longer matches the code; what the parameters do inside the estimators is " +
                "described in [ALGORITHM.md, section 11](${algorithmLink("## 11. ")}).",
        )
        appendColumns()
        appendStorageNotes()
        appendLine("## Groups")
        appendLine()
        SettingsCatalog.sections.forEach { section ->
            val title = text(section.title)
            appendLine("- [$title](#${slug(title)}): ${text(section.summary)}")
        }
        appendLine()
    }

    /** What the columns of the tables mean. */
    private fun StringBuilder.appendColumns() {
        val backup = text(R.string.settings_actions_title)
        val export = text(R.string.settings_action_export)
        val recompute = text(R.string.settings_stale_recompute)
        val overwrite = SettingsCatalog.spec("write.overwritePolicy")?.title?.let(::text)
        appendLine("| Column | Meaning |")
        appendLine("|---|---|")
        appendLine("| Setting | The label on the Settings screen. |")
        appendLine(
            "| Key in the JSON export | Where the value is in the file written by **$export** (card **$backup** at the " +
                "top of the Settings tab). Each dot is a nested object: `sources.minSessionMin` is " +
                "`{\"sources\": {\"minSessionMin\": 90}}`. |",
        )
        appendLine("| Default | The value of a new installation, as the export writes it, and the unit shown next to the field. |")
        appendLine(
            "| Allowed values | What the validators accept. A value outside is not stored: the screen shows the problem " +
                "below the field, and an import that contains one is rejected as a whole. |",
        )
        appendLine("| Effect | The hint shown below the control. |")
        appendLine(
            "| In params hash | **yes** when changing the value changes the params hash stored with every estimate. A " +
                "written night whose params hash or algorithm version differs from the current one is *stale*: after such " +
                "a change the Settings screen says how many nights are now stale and offers **$recompute**; what later " +
                "runs do with stale nights depends on **$overwrite** (`write.overwritePolicy`). |",
        )
        appendLine()
    }

    /** What else the params hash covers, how import and storage treat the values. */
    private fun StringBuilder.appendStorageNotes() {
        val import = text(R.string.settings_action_import)
        val reset = text(R.string.settings_action_reset)
        val personal = SettingsCatalog.spec("algo.personal.enabled")?.title?.let(::text)
        val features = text(R.string.settings_section_features)
        appendParagraph(
            "Besides the values marked **yes**, the params hash covers the fingerprint of the bundled hybrid model, the " +
                "fingerprint of the personal model in use while **$personal** (`algo.personal.enabled`) is on, and which " +
                "optional channels (SpO2, respiratory rate, HRV) are both switched on under **$features** and granted in " +
                "Health Connect.",
        )
        appendParagraph(
            "**$import** accepts a complete export or any part of one: missing keys take their defaults, unknown keys " +
                "are ignored, and a value of the wrong type or an unknown option name rejects the file. Every value is " +
                "checked before anything is stored. The app stores only the values that differ from the defaults, so a " +
                "default that a later version changes (for example a retrained one) applies to every value you never " +
                "changed, while a value you set to something else stays as you set it. An export contains every value, " +
                "defaults included, so importing a complete export stores every value that differs from this version's " +
                "defaults, older defaults included, and those values then no longer follow updates; to carry only your " +
                "own changes into a newer version, delete the other keys from the file before importing it. " +
                "**$reset** returns every " +
                "setting, the sources included, to the defaults below. Demo mode of debug builds is not a setting " +
                "([Screenshots and demo mode](SCREENSHOTS.md)).",
        )
    }

    private fun StringBuilder.appendSection(section: SettingsSection) {
        appendLine("## ${text(section.title)}")
        appendLine()
        val shown = if (section.expandedByDefault) "Shown expanded." else "Collapsed until you open it."
        val algorithm =
            ALGORITHM_SECTIONS[section.id]?.let { heading ->
                " Algorithm: [ALGORITHM.md, section ${sectionNumber(heading)}](${algorithmLink(heading)})."
            }
        appendParagraph("${text(section.summary)}. $shown${algorithm.orEmpty()}")
        appendLine("| Setting | Key in the JSON export | Default | Allowed values | Effect | In params hash |")
        appendLine("|---|---|---|---|---|---|")
        var previousEffect: String? = null
        rows(section).forEach { row ->
            val effect = if (row.effect.isNotEmpty() && row.effect == previousEffect) "As above." else row.effect
            previousEffect = row.effect
            val hash =
                when (row.inParamsHash) {
                    true -> "yes"
                    false -> "no"
                    null -> ""
                }
            val keys = row.keys.joinToString("<br>") { code(it) }
            appendLine("| ${row.setting} | $keys | ${row.default} | ${row.allowed} | ${plain(effect)} | $hash |")
        }
        appendLine()
        if (section.items.any { it == SettingsItem.SourcesLink }) {
            appendParagraph(
                "The three source lists are edited on the **${text(R.string.sources_title)}** screen (**" +
                    "${text(R.string.settings_sources_link_title)}** above). On every save and import, duplicate package " +
                    "names are removed and every enabled or manually added package that is missing from " +
                    "`sources.sourcePriority` is appended to it.",
            )
        }
    }

    private fun StringBuilder.appendParagraph(text: String) {
        appendLine(text)
        appendLine()
    }

    // ------------------------------------------------------------------------------------------------ rows

    private fun rows(section: SettingsSection): List<ReferenceRow> =
        section.items.flatMap { item ->
            when (item) {
                is SettingsItem.Field -> listOf(row(item.spec))
                is SettingsItem.Subheader -> listOf(ReferenceRow("**${plain(text(item.title))}**", emptyList(), "", "", "", null))
                SettingsItem.SourcesLink -> sourceListRows()
                SettingsItem.LogLink -> emptyList()
                is SettingsItem.EmissionTable -> item.rows.flatMap { row -> row.cells.flatMap { listOf(it.mean, it.sd) } }.map(::row)
                is SettingsItem.TransitionWeights -> item.rows.flatMap { it.weights }.map(::row)
            }
        }

    private fun row(spec: SettingSpec): ReferenceRow =
        ReferenceRow(
            setting = plain(text(spec.title)),
            keys = spec.paths,
            default = defaultOf(spec),
            allowed = allowedOf(spec),
            effect = text(spec.hint),
            inParamsHash = paramsHash(changed(spec)) != defaultHash,
        )

    /** The source lists of the Sources screen ([SettingsCatalog.SOURCES_SCREEN_PATHS]). */
    private fun sourceListRows(): List<ReferenceRow> {
        val sources = text(R.string.settings_sources_link_title)
        val screen = text(R.string.sources_title)
        val lists =
            listOf(
                SourceList("sources.sourcePackages", "$sources ($screen screen): enabled apps", R.string.sources_priority_hint) { s, v ->
                    s.copy(sources = s.sources.copy(sourcePackages = v))
                },
                SourceList("sources.sourcePriority", "$sources ($screen screen): priority order", R.string.sources_priority_hint) { s, v ->
                    s.copy(sources = s.sources.copy(sourcePriority = v))
                },
                SourceList("sources.manualPackages", text(R.string.sources_manual_title), R.string.sources_manual_hint) { s, v ->
                    s.copy(sources = s.sources.copy(manualPackages = v))
                },
            )
        check(lists.map { it.path }.toSet() == SettingsCatalog.SOURCES_SCREEN_PATHS) { "the source lists changed" }
        return lists.map { list ->
            val constraints = Constraints()
            constraints.collect(list.path, problemsOf(list.write(defaults, listOf(INVALID_PACKAGE))))
            val pattern = constraints.plain.single()
            ReferenceRow(
                setting = plain(list.setting),
                keys = listOf(list.path),
                default = code(jsonAt(defaultJson, list.path).toString()),
                allowed = "list of package names matching ${code(pattern)}",
                effect = text(list.effect),
                inParamsHash = paramsHash(list.write(defaults, listOf(EXAMPLE_PACKAGE))) != defaultHash,
            )
        }
    }

    // ------------------------------------------------------------------------------------------------ defaults

    private fun defaultOf(spec: SettingSpec): String {
        val value = jsonAt(defaultJson, spec.path)
        return when (spec) {
            is ChoiceSpec -> "${code(value.toString())} (${plain(text(spec.options.single { it.key == spec.read(defaults) }.label))})"
            is TimeSpec -> "${code(value.toString())} (${clock(spec.read(defaults))})"
            is TextSpec -> if (value is JsonNull) "`null` (“${plain(text(spec.placeholder))}”)" else code(value.toString())
            is OptionalDoubleSpec -> optionalDefault(value, formatSettingNumber(spec.inherited(defaults)), spec.unit)
            is OptionalIntSpec -> optionalDefault(value, spec.inherited(defaults).toString(), spec.unit)
            is RangeSpec -> "${code(value.toString())} – ${code(jsonAt(defaultJson, spec.maxPath).toString())}"
            is IntSpec -> withUnit(code(value.toString()), spec.unit)
            is DoubleSpec -> withUnit(code(value.toString()), spec.unit)
            is SwitchSpec -> code(value.toString())
        }
    }

    /** The default of an optional nap override: its value, or `null` with the night's value [inherited] it stands for. */
    private fun optionalDefault(
        value: JsonElement,
        inherited: String,
        unit: UiText?,
    ): String =
        if (value is JsonNull) {
            "`null` (${plain(withUnit(text(UiText.of(R.string.settings_same_as_nights_value, inherited)), unit))})"
        } else {
            withUnit(code(value.toString()), unit)
        }

    private fun withUnit(
        value: String,
        unit: UiText?,
    ): String = if (unit == null) value else "$value ${plain(text(unit))}"

    // ------------------------------------------------------------------------------------------------ allowed values

    private fun allowedOf(spec: SettingSpec): String =
        when (spec) {
            is SwitchSpec -> "`true`, `false`"
            is ChoiceSpec -> choiceValues(spec)
            is RangeSpec -> rangeAllowed(spec)
            else -> numberOrTextAllowed(spec)
        }

    /** Every option of [spec] as the JSON value the export writes for it, with its label. */
    private fun choiceValues(spec: ChoiceSpec): String =
        spec.options.joinToString(", ") { option ->
            val value = jsonAt(encode(spec.write(defaults, option.key)), spec.path)
            "${code(value.toString())} (${plain(text(option.label))})"
        }

    private fun numberOrTextAllowed(spec: SettingSpec): String {
        val atDefaults = probe(spec, defaults)
        val elsewhere = probe(spec, alternative)
        val base =
            when {
                atDefaults.render() == elsewhere.render() -> {
                    atDefaults.render()
                }

                atDefaults.bounds() == elsewhere.bounds() -> {
                    // A relation to a nap override that replaces the night's value when it is set.
                    (atDefaults.bounds() + relationsEitherWay(atDefaults.relations.keys, elsewhere.relations.keys)).joinToString("; ")
                }

                else -> {
                    // The bound moves with another setting (e.g. "longer than one epoch"): the UI's wording, the value at the defaults.
                    val bounds = uiBounds(spec)?.let(::text)
                    val value = atDefaults.render()
                    if (bounds != null) "$bounds ($value at the defaults)" else "$value at the defaults (depends on other settings)"
                }
            }
        return when (spec) {
            is IntSpec, is TimeSpec -> "$base (whole number)"
            is OptionalDoubleSpec -> "`null` (${plain(text(R.string.option_same_as_nights))}) or a number: $base"
            is OptionalIntSpec -> "`null` (${plain(text(R.string.option_same_as_nights))}) or a whole number: $base"
            else -> base
        }
    }

    /**
     * The relations of the defaults ([atDefaults]) and of [alternative], where a relation of the alternative replaces the
     * one of the defaults with the same comparison: `≤ \`nap override\` if that is set, else ≤ \`night value\``.
     */
    private fun relationsEitherWay(
        atDefaults: Set<String>,
        alternative: Set<String>,
    ): List<String> {
        val unpaired = (atDefaults - alternative).toMutableList()
        val replaced =
            (alternative - atDefaults).map { relation ->
                val night = unpaired.firstOrNull { it.first() == relation.first() } ?: error("no counterpart of \"$relation\"")
                unpaired -= night
                "$relation if that is set, else $night"
            }
        check(unpaired.isEmpty()) { "relations without a counterpart: $unpaired" }
        return atDefaults.intersect(alternative).toList() + replaced
    }

    private fun rangeAllowed(spec: RangeSpec): String {
        val (min, max) = spec.readMin(defaults) to spec.readMax(defaults)
        val lower = Constraints()
        val upper = Constraints()
        listOf(-HUGE, HUGE).forEach { v ->
            lower.collect(spec.path, problemsOf(spec.write(defaults, v, max)))
            upper.collect(spec.maxPath, problemsOf(spec.write(defaults, min, v)))
        }
        val ordered = lower.relations.keys.any { spec.maxPath in it } || upper.relations.keys.any { spec.path in it }
        val bounds = lower.withoutRelationsTo(spec.maxPath).render()
        check(bounds == upper.withoutRelationsTo(spec.path).render()) { "${spec.path}: the two ends have different ranges" }
        return if (ordered) "each $bounds; lower ≤ upper" else "each $bounds"
    }

    /** The constraints the validators report for the value of [spec] written on [base] with values outside any range. */
    private fun probe(
        spec: SettingSpec,
        base: AppSettings,
    ): Constraints {
        val constraints = Constraints()
        probes(spec, base).forEach { constraints.collect(spec.path, problemsOf(it)) }
        if (constraints.isEmpty() && spec is DoubleSpec) constraints.collect(spec.path, problemsOf(spec.write(base, Double.NaN)))
        if (constraints.isEmpty() && spec is OptionalDoubleSpec) constraints.collect(spec.path, problemsOf(spec.write(base, Double.NaN)))
        return constraints
    }

    private fun probes(
        spec: SettingSpec,
        base: AppSettings,
    ): List<AppSettings> =
        when (spec) {
            is IntSpec -> INT_PROBES.map { spec.write(base, it) }
            is TimeSpec -> listOf(-1, MINUTES_PER_DAY, HUGE.toInt()).map { spec.write(base, it) }
            is DoubleSpec -> listOf(-HUGE, HUGE).map { spec.write(base, it) }
            is OptionalDoubleSpec -> listOf(-HUGE, HUGE).map { spec.write(base, it) }
            is OptionalIntSpec -> INT_PROBES.map { spec.write(base, it) }
            is TextSpec -> listOf(" ", "x".repeat(SettingsLimits.TITLE_TEMPLATE_MAX_LENGTH + 1)).map { spec.write(base, it) }
            is SwitchSpec, is ChoiceSpec, is RangeSpec -> emptyList()
        }

    private fun uiBounds(spec: SettingSpec): UiText? =
        when (spec) {
            is DoubleSpec -> spec.bounds
            is OptionalDoubleSpec -> spec.bounds
            else -> null
        }

    // ------------------------------------------------------------------------------------------------ params hash

    /** The settings with the value of [spec] changed (validity does not matter, only the hash). */
    private fun changed(spec: SettingSpec): AppSettings =
        when (spec) {
            is SwitchSpec -> spec.write(defaults, !spec.read(defaults))
            is ChoiceSpec -> spec.write(defaults, spec.options.first { it.key != spec.read(defaults) }.key)
            is IntSpec -> spec.write(defaults, spec.read(defaults) + 2)
            is DoubleSpec -> spec.write(defaults, spec.read(defaults) + CHANGE)
            is OptionalDoubleSpec -> spec.write(defaults, (spec.read(defaults) ?: spec.inherited(defaults)) + CHANGE)
            is OptionalIntSpec -> spec.write(defaults, (spec.read(defaults) ?: spec.inherited(defaults)) - 1)
            is TimeSpec -> spec.write(defaults, (spec.read(defaults) + 1) % MINUTES_PER_DAY)
            is TextSpec -> spec.write(defaults, "Stages {version}")
            is RangeSpec -> spec.write(defaults, spec.readMin(defaults) - CHANGE / 10, spec.readMax(defaults) + CHANGE / 10)
        }

    // ------------------------------------------------------------------------------------------------ helpers

    private fun text(id: Int): String = resources.getString(id)

    private fun text(value: UiText): String = value.resolve(resources)

    private fun algorithmLink(headingPrefix: String): String {
        val anchor =
            algorithmAnchors.firstOrNull { it.startsWith(headingPrefix) }?.substringAfter(ANCHOR_SEPARATOR)
                ?: error("ALGORITHM.md has no heading starting with \"$headingPrefix\"")
        return "../ALGORITHM.md#$anchor"
    }

    private fun sectionNumber(headingPrefix: String): String = headingPrefix.trimStart('#').trim().trimEnd('.')

    private fun clock(minutes: Int): String = "%02d:%02d".format(minutes / MINUTES_PER_HOUR, minutes % MINUTES_PER_HOUR)

    private companion object {
        const val REGENERATE: String =
            "mise exec -- ./gradlew :app:testDebugUnitTest --tests '*SettingsReferenceTest' -PrecordSettingsReference"
        const val HUGE = 1e9
        const val CHANGE = 0.25
        const val MINUTES_PER_DAY = 1440
        const val MINUTES_PER_HOUR = 60
        const val INVALID_PACKAGE = "not a package"
        const val EXAMPLE_PACKAGE = "com.example.watch"
        const val ANCHOR_SEPARATOR = "\u0000"
        val INT_PROBES: List<Int> = listOf(-1_000_000, 1_000_000, 0, 2, 4)
        val GRANTED: Set<String> = HealthPermissions.REQUIRED + HealthPermissions.OPTIONAL + HealthPermissions.SPECIAL

        /** The ALGORITHM.md section of each group, by the start of its heading. */
        val ALGORITHM_SECTIONS: Map<String, String> =
            mapOf(
                "estimator" to "### 13.2 ",
                "naps" to "## 18. ",
                "preprocess" to "## 3. ",
                "features" to "## 4. ",
                "rules" to "## 5. ",
                "hmm_emissions" to "## 6. ",
                "hmm_transitions" to "## 6. ",
                "hmm_priors" to "## 6. ",
                "hybrid" to "## 7. ",
                "post" to "## 8. ",
                "naps_algorithm" to "## 18. ",
                "personal" to "## 10. ",
            )

        fun encode(settings: AppSettings): JsonElement = SettingsJson.export.encodeToJsonElement(AppSettings.serializer(), settings)

        fun paramsHash(settings: AppSettings): String = ParamsHasher.hash(settings.algo, extra = OutputOptions.hashExtra(settings, GRANTED))

        /** Every problem both validators report for [settings], as (settings path, constraint). */
        fun problemsOf(settings: AppSettings): List<Pair<String, String>> =
            SettingsValidator.validate(settings).errors.map { it.path to it.constraint } +
                AlgoParamsValidator.problems(settings.algo).map { "algo.${it.path}" to it.constraint }

        fun jsonAt(
            root: JsonElement,
            path: String,
        ): JsonElement = path.split('.').fold(root) { element, key -> element.jsonObject[key] ?: error("no value at $path") }

        /**
         * The headings of [markdown] outside code blocks, each as `<heading line>\u0000<GitHub anchor>` (GitHub's
         * slugs: lower case, punctuation removed, spaces as hyphens, `-1`, `-2`, ... for repeated slugs).
         */
        fun headingAnchors(markdown: String): List<String> {
            var fenced = false
            val seen = mutableMapOf<String, Int>()
            return markdown.lines().mapNotNull { line ->
                if (line.startsWith("```")) fenced = !fenced
                val heading =
                    Regex("^#{1,6} (.+)$")
                        .matchEntire(line)
                        ?.takeIf { !fenced }
                        ?.groupValues
                        ?.get(1) ?: return@mapNotNull null
                val base = slug(heading)
                val count = seen.getOrDefault(base, 0)
                seen[base] = count + 1
                line + ANCHOR_SEPARATOR + if (count == 0) base else "$base-$count"
            }
        }

        fun slug(heading: String): String =
            heading
                .lowercase()
                .filter { it.isLetterOrDigit() || it == ' ' || it == '-' || it == '_' }
                .replace(' ', '-')

        /** [value] as a code span inside a table cell. */
        fun code(value: String): String = "`" + value.replace("|", "\\|") + "`"

        /** [value] as plain text inside a table cell. */
        fun plain(value: String): String =
            value
                .replace("|", "\\|")
                .replace("<", "&lt;")
                .replace("\n", " ")
    }
}

/**
 * One row of a reference table: a setting, or a sub-heading of a group (bold [setting], everything else empty).
 *
 * @property inParamsHash whether a change of the value changes the params hash; null for a sub-heading.
 */
private data class ReferenceRow(
    val setting: String,
    val keys: List<String>,
    val default: String,
    val allowed: String,
    val effect: String,
    val inParamsHash: Boolean?,
)

/** A source list of the Sources screen: its key, its description and how to replace it. */
private class SourceList(
    val path: String,
    val setting: String,
    val effect: Int,
    val write: (AppSettings, List<String>) -> AppSettings,
)

/**
 * The constraints the validators report for one settings path, in a readable form: plain bounds ([plain]: `10–720`,
 * `≥ 0`, `odd, 1–31`) and relations to other values ([relations]: `≤ \`algo.preprocess.maxBpm\`` to the bound it
 * stands for at the probed values, `≤ 180`).
 */
private class Constraints {
    val plain = LinkedHashSet<String>()
    val relations = LinkedHashMap<String, String>()
    private var finite = false

    fun isEmpty(): Boolean = plain.isEmpty() && relations.isEmpty() && !finite

    /** Adds what [problems] say about [path]: its own constraints, and relations stated at another value about it. */
    fun collect(
        path: String,
        problems: List<Pair<String, String>>,
    ) {
        problems.forEach { (at, constraint) ->
            val relation = RELATION.matchEntire(constraint)
            when {
                at == path || at.startsWith("$path[") -> own(constraint, relation)
                relation != null && settingsPath(relation.groupValues[2]) == path -> reverse(at, relation.groupValues[1])
            }
        }
    }

    private fun own(
        constraint: String,
        relation: MatchResult?,
    ) {
        when {
            relation != null -> {
                val (op, other, value) = relation.destructured
                val comparison = SettingsChecks.pretty(op)
                relations["$comparison `${settingsPath(other)}`"] = "$comparison ${SettingsChecks.pretty(value)}"
            }

            constraint in FINITE -> {
                finite = true
            }

            else -> {
                plain += SettingsChecks.pretty(constraint)
            }
        }
    }

    /** `other <= path` is `path ≥ other`; `other >= path` is `path ≤ other`. */
    private fun reverse(
        other: String,
        op: String,
    ) {
        val flipped = if (op == "<=") ">=" else "<="
        relations.putIfAbsent("${SettingsChecks.pretty(flipped)} `$other`", "")
    }

    /** A copy without the relations that mention [path]. */
    fun withoutRelationsTo(path: String): Constraints =
        Constraints().also { copy ->
            copy.plain += plain
            relations.filterKeys { path !in it }.forEach { (k, v) -> copy.relations[k] = v }
            copy.finite = finite
        }

    /** The plain bounds, without those that a relation already states (`≥ 0.03` for `≥ \`algo.post.sanityDeepMin\``). */
    fun bounds(): List<String> {
        val shadowed = relations.values.toSet()
        return mergeOpenLowerBound(plain.filterNot { it in shadowed })
    }

    /** The [bounds] and the relations joined with "; ". */
    fun render(): String {
        val parts = bounds() + relations.keys
        return when {
            parts.isNotEmpty() -> parts.joinToString("; ")
            finite -> "any finite number"
            else -> "any value (not checked)"
        }
    }

    private companion object {
        val RELATION = Regex("""(<=|>=) (\S+) \((.*)\)""")
        val FINITE = setOf("finite number", "a finite number")
        val OPEN_LOWER = Regex("""> (\S+)""")
        val CLOSED_RANGE = Regex("""(\S+)–(\S+)""")
        val TOP_LEVEL = listOf("sources.", "schedule.", "write.", "algo.", "debug.")

        /** A path of [AlgoParamsValidator] (`preprocess.maxBpm`) as a settings path (`algo.preprocess.maxBpm`). */
        fun settingsPath(path: String): String = if (TOP_LEVEL.any { path.startsWith(it) }) path else "algo.$path"

        /** `> 0` and `0–1` together are `> 0 and ≤ 1`. */
        fun mergeOpenLowerBound(bounds: List<String>): List<String> {
            val open = bounds.firstNotNullOfOrNull { OPEN_LOWER.matchEntire(it) }
            val range =
                open?.let { lower ->
                    bounds.firstNotNullOfOrNull { b -> CLOSED_RANGE.matchEntire(b)?.takeIf { it.groupValues[1] == lower.groupValues[1] } }
                }
            if (open == null || range == null) return bounds
            val merged = "> ${open.groupValues[1]} and ≤ ${range.groupValues[2]}"
            return bounds.map { if (it == open.value) merged else it }.filterNot { it == range.value }
        }
    }
}
