/** One minute in ms. */
const val MINUTE_MS: Long = 60_000L

/** One hour in ms. */
const val HOUR_MS: Long = 60 * MINUTE_MS

/** One day in ms. */
const val DAY_MS: Long = 24 * HOUR_MS

/** 2026-10-13T00:00:00Z. */
const val MIDNIGHT: Long = PipelineHarness.DEFAULT_START_MS

/** "Now" in most tests: 2026-10-13T12:00:00Z (the last night ended this morning). */
const val NOON: Long = MIDNIGHT + 12 * HOUR_MS

/** The default sleep source (OHealth). */
const val OHEALTH: String = OHEALTH_PACKAGE

/** Another sleep-tracking app. */
const val OTHER_APP: String = "com.example.sleeptracker"

/** A third sleep-tracking app. */
const val THIRD_APP: String = "org.example.thirdtracker"

/** Our own package. */
const val OWN: String = FakeHealthRepository.DEFAULT_OWN_PACKAGE

/** Start of the night that began [daysAgo] days before [MIDNIGHT], at 23:00 UTC. */
fun nightStart(daysAgo: Int): Long = MIDNIGHT - daysAgo * DAY_MS - HOUR_MS

/**
 * Heart rate with a stage-like pattern (for the fake estimator: < 52 DEEP, < 58 LIGHT, < 66 REM, else AWAKE),
 * repeating every 90 minutes after [sessionStartMs]: 15 min LIGHT, 25 min DEEP, 25 min LIGHT, 20 min REM, 5 min AWAKE.
 */
fun cyclingBpm(sessionStartMs: Long): (Long) -> Double =
    { t ->
        val minute = Math.floorMod((t - sessionStartMs) / MINUTE_MS, 90L)
        when {
            minute < 15 -> 55.0
            minute < 40 -> 49.0
            minute < 65 -> 56.0
            minute < 85 -> 62.0
            else -> 72.0
        }
    }

/**
 * Adds a sleep session of [packageName] plus heart rate (every 2 min, from 30 min before to 30 min after) and a few
 * steps, as OHealth would write them.
 */
fun FakeHealthRepository.addNight(
    packageName: String,
    startMs: Long,
    durationMs: Long = 8 * HOUR_MS,
    stages: List<HcStage> = emptyList(),
    startZoneOffsetSec: Int? = 0,
    endZoneOffsetSec: Int? = 0,
    withHeartRate: Boolean = true,
): HcSleepSession {
    val session = addSleepSession(packageName, startMs, startMs + durationMs, stages, startZoneOffsetSec, endZoneOffsetSec)
    if (withHeartRate) addHeartRate(packageName, startMs - 30 * MINUTE_MS, startMs + durationMs + 30 * MINUTE_MS, bpm = cyclingBpm(startMs))
    return session
}

/** Runs [block] with a fresh [PipelineHarness] whose clock is at [now], in virtual time. */
fun harnessTest(
    dir: File,
    now: Long = NOON,
    block: suspend TestScope.(PipelineHarness) -> Unit,
) = runTest {
    val harness = PipelineHarness(backgroundScope, dir, StandardTestDispatcher(testScheduler), startMs = now)
    block(harness)
}

/**
 * A synthetic night stored in a [FakeHealthRepository].
 *
 * @property session the sleep session as stored.
 * @property night the generated night (input and true hypnogram).
 */
data class StoredSyntheticNight(
    val session: HcSleepSession,
    val night: SyntheticNight,
)

/**
 * Adds a night generated by core-algo's [SyntheticNightGenerator] (seed [seed], session starting at [startMs]): the
 * sleep session of [packageName] (with [stages], none by default), every heart-rate sample as a one-sample record of
 * [heartRatePackage] and the step records; [outlierRate] is the generator's share of ±40 bpm spikes.
 */
@Suppress("LongParameterList") // Test setup with defaults.
fun FakeHealthRepository.addSyntheticNight(
    packageName: String,
    startMs: Long,
    seed: Long,
    person: SyntheticPerson = SyntheticPerson(),
    heartRatePackage: String = packageName,
    outlierRate: Double = SyntheticOptions().outlierRate,
    stages: (SyntheticNight) -> List<HcStage> = { emptyList() },
): StoredSyntheticNight {
    val night =
        SyntheticNightGenerator(
            seed,
        ).generate(SyntheticOptions(sessionStartMs = startMs, person = person, outlierRate = outlierRate))
    val session = addSleepSession(packageName, night.input.sessionStartMs, night.input.sessionEndMs, stages(night))
    night.input.heartRate.forEach { addHeartRateSeries(heartRatePackage, listOf(it)) }
    night.input.steps.forEach { addSteps(heartRatePackage, it.startMs, it.endMs, it.count) }
    return StoredSyntheticNight(session, night)
}

/** [truth] as Health Connect stages (AWAKE 1, LIGHT 4, DEEP 5, REM 6; UNKNOWN 0). */
fun hcStagesOf(truth: List<StageInterval>): List<HcStage> =
    truth.map { HcStage(it.startMs, it.endMs, StageMapping.toHcType(it.stage, awakeAsLight = false)) }
