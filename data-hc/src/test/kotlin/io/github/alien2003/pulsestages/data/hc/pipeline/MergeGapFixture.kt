package io.github.alien2003.pulsestages.data.hc.pipeline

import io.github.alien2003.pulsestages.algo.model.TimeSpan
import io.github.alien2003.pulsestages.algo.params.AlgoParams
import io.github.alien2003.pulsestages.algo.params.NapModeParams
import io.github.alien2003.pulsestages.data.hc.HcSleepSession
import io.github.alien2003.pulsestages.data.hc.testutil.OHEALTH
import io.github.alien2003.pulsestages.data.local.settings.SourceSettings
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.double
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.long
import java.io.File

/**
 * The grouping fixture of gate G4 of docs/prereg/prereg-merge-gap.md (`tools/train/tests/data/mergegap-grouping.json`,
 * generated by `pulsetrain.mergegap.grouping_fixture()`): per case and arm, the groups and the continuation thresholds
 * that the Python emulation of [NightCandidateBuilder] computes. The Kotlin tests check the builder and
 * [SourceSettlement] against the same file; the build passes its path in the system property [PROPERTY].
 */
internal object MergeGapFixture {
    /** System property with the fixture's absolute path (data-hc/build.gradle.kts). */
    const val PROPERTY: String = "pulsestages.mergegapGroupingFixture"

    /** An arm: `sources.mergeGapMin` and `sources.continuationGapMin`. */
    data class Arm(
        val name: String,
        val mergeGapMin: Int,
        val continuationGapMin: Int,
    )

    /** One expected group: sorted uuids, span, forced-AWAKE gaps and mode (IGNORED, NAP or NIGHT). */
    data class Group(
        val uuids: List<String>,
        val startMs: Long,
        val endMs: Long,
        val forcedAwake: List<TimeSpan>,
        val mode: String,
    )

    /** What one arm gives for a case. */
    data class Expected(
        val groups: List<Group>,
        val thresholds: Map<String, Long>,
    )

    /** One case: one package's sessions (OHealth) with `sources.minSessionMin` and `napMode.maxSessionMin`. */
    data class Case(
        val name: String,
        val minSessionMin: Int,
        val napMaxSessionMin: Double,
        val sessions: List<HcSleepSession>,
        val expected: Map<String, Expected>,
    )

    /** The whole file. */
    data class Fixture(
        val arms: List<Arm>,
        val dataMarginExtraMs: Long,
        val cases: List<Case>,
    )

    /** Reads the fixture (the path of [PROPERTY], or the repository path relative to the module directory). */
    fun load(): Fixture {
        val path = System.getProperty(PROPERTY) ?: "../tools/train/tests/data/mergegap-grouping.json"
        val root = Json.parseToJsonElement(File(path).readText()).jsonObject
        val arms =
            root.getValue("arms").jsonObject.map { (name, value) ->
                val a = value.jsonObject
                Arm(name, a.int("mergeGapMin"), a.int("continuationGapMin"))
            }
        val cases = root.getValue("cases").jsonArray.map { case(it.jsonObject) }
        return Fixture(arms, root.getValue("dataMarginExtraMs").jsonPrimitive.long, cases)
    }

    /** The settings of [arm] for [case]: OHealth enabled (the default), its minimum session length and gaps. */
    fun sources(
        case: Case,
        arm: Arm,
    ): SourceSettings =
        SourceSettings(
            minSessionMin = case.minSessionMin,
            mergeGapMin = arm.mergeGapMin,
            continuationGapMin = arm.continuationGapMin,
        )

    /** The algorithm parameters of [case]: the defaults with its `napMode.maxSessionMin`. */
    fun algo(case: Case): AlgoParams = AlgoParams(napMode = NapModeParams(maxSessionMin = case.napMaxSessionMin))

    /** What [NightCandidateBuilder.build] gave, as the fixture's groups sorted by start (ignored ones included). */
    fun groupsOf(
        set: CandidateSet,
        algo: AlgoParams,
    ): List<Group> {
        val estimated =
            set.candidates.map { night ->
                Group(night.sourceUuids, night.startMs, night.endMs, night.forcedAwake, night.mode(algo).name)
            }
        val ignored =
            set.skipped.map { night ->
                Group(
                    night.sessions.map { it.uuid }.sorted(),
                    night.startMs,
                    night.endMs,
                    gapsBetween(night.sessions.map { TimeSpan(it.startMs, it.endMs) }),
                    "IGNORED",
                )
            }
        return (estimated + ignored).sortedWith(compareBy({ it.startMs }, { it.endMs }))
    }

    private fun case(c: JsonObject): Case {
        val sessions =
            c.getValue("sessions").jsonArray.map {
                val s = it.jsonObject
                HcSleepSession(s.string("uuid"), OHEALTH, s.long("startMs"), s.long("endMs"), 0, 0, emptyList(), null, null, null, 0, 0)
            }
        val expected =
            c.getValue("expected").jsonObject.mapValues { (_, value) ->
                val e = value.jsonObject
                Expected(
                    groups = e.getValue("groups").jsonArray.map { group(it.jsonObject) },
                    thresholds = e.getValue("thresholds").jsonObject.mapValues { it.value.jsonPrimitive.long },
                )
            }
        return Case(
            c.string("name"),
            c.int("minSessionMin"),
            c.getValue("napMaxSessionMin").jsonPrimitive.double,
            sessions,
            expected,
        )
    }

    private fun group(g: JsonObject): Group =
        Group(
            uuids = g.getValue("uuids").jsonArray.map { it.jsonPrimitive.content },
            startMs = g.long("startMs"),
            endMs = g.long("endMs"),
            forcedAwake =
                g.getValue("forcedAwake").jsonArray.map { span ->
                    val (a, b) = span.jsonArray.map { it.jsonPrimitive.long }
                    TimeSpan(a, b)
                },
            mode = g.string("mode"),
        )

    private fun JsonObject.string(key: String): String = getValue(key).jsonPrimitive.content

    private fun JsonObject.int(key: String): Int = getValue(key).jsonPrimitive.int

    private fun JsonObject.long(key: String): Long = getValue(key).jsonPrimitive.long
}
