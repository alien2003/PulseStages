def test_cli_renders_a_run(tmp_path, capsys):
    run = tmp_path / "out" / "r3"
    write_json(run / "trained_defaults.json", {"estimator": "HYBRID", "hybrid": HYBRID})
    write_json(run / "summary.json", {"meta": {"run": "r3", "createdAt": "2026-10-13T01:02:03Z"},
                                      "selection": SELECTION})
    assert train.main(["defaults", "--run", "r3", "--out-root", str(tmp_path / "out")]) == 0
    assert "--run r3" in capsys.readouterr().out
    target = tmp_path / "TrainedDefaults.kt"
    assert train.main(["defaults", "--run", "r3", "--out-root", str(tmp_path / "out"), "--output", str(target)]) == 0
    assert target.read_text().startswith("// Generated by tools/train/train.py defaults --run r3")
    assert kotlin_defaults.KOTLIN_PATH.name == "TrainedDefaults.kt"


def test_time_prior_is_always_generated():
    from pulsetrain.stats import SPEC_TIME_PRIOR, TIME_PRIOR_KEYS

    src = render({"estimator": "HYBRID", "hybrid": HYBRID}, SELECTION, "r1", "2026-10-13", "Walch")
    assert "val HMM_TIME_PRIOR: HmmTimePrior = HmmTimePrior()" in src
    hmm = {"emissions": PHYSIOLOGY_EMISSIONS, "meanBouts": DEFAULT_MEAN_BOUTS, "transitions": DEFAULT_TRANSITIONS}
    sel = dict(SELECTION, hmm={"table": 0.08, "trained": 0.09, "trainedPool": "walch", "useTrained": True})
    old = render({"estimator": "HMM", "hybrid": HYBRID, "hmm": hmm}, sel, "r", "2026", "x")   # runs before the
    assert "val HMM_TIME_PRIOR: HmmTimePrior = HmmTimePrior()" in old and "not estimated" in old   # time prior
    tp = {k: v * 1.1 + 0.0123 for k, v in SPEC_TIME_PRIOR.items()}
    new = render({"estimator": "HMM", "hybrid": HYBRID, "hmm": {**hmm, **tp}}, sel, "r", "2026", "x")
    assert "val HMM_TIME_PRIOR: HmmTimePrior =" in new and "HmmTimePrior()" not in new
    assert set(re.findall(r"^\s+(\w+) = [-\d.e]+,$", new.split("HMM_TIME_PRIOR")[1], re.M)) == set(
        data_class_fields("HmmTimePrior")) == set(TIME_PRIOR_KEYS)
    assert f"deepTimeSlope = {tp['deepTimeSlope']!r}," in new
    with pytest.raises(DefaultsError, match="incomplete"):
        render({"estimator": "HMM", "hybrid": HYBRID, "hmm": {**hmm, "deepTimeSlope": 1.0}}, sel, "r", "2026", "x")


