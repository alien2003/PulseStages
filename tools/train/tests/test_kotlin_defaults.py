SELECTION = {
    "estimatorScores": {"RULES": 0.07, "HMM": 0.08, "HYBRID": 0.29},
    "classifier": {"chosen": "lr", "config": "walch"},
    "decoderParams": {"params": {}, "count": 40, "folds": 62},
    "hmm": {"table": 0.08, "trained": 0.06, "trainedPool": "walch", "useTrained": False},
}
HYBRID = {"durationModel": "GEOMETRIC", "emissionWeight": 0.7, "timePriorWeight": 0.0}


def test_physiology_table_kept_when_trained_hmm_loses():
    src = render({"estimator": "HYBRID", "hybrid": HYBRID}, SELECTION, "r1", "2026-10-13T00:00:00Z", "Walch 1.0.0")
    head = src.splitlines()[:2]
    assert head[0] == "// Generated by tools/train/train.py defaults --run r1 from"
    assert head[1] == "// Walch 1.0.0, 2026-10-13; do not edit by hand."
    assert "`mise exec -- python -I tools/train/train.py defaults --run <run> --write`" in src   # not wrapped
    assert "val ESTIMATOR: EstimatorType = EstimatorType.HYBRID" in src
    assert "val HYBRID_DURATION_MODEL: DurationModel = DurationModel.GEOMETRIC" in src
    assert "const val HYBRID_EMISSION_WEIGHT: Double = 0.7" in src
    assert "const val HYBRID_TIME_PRIOR_WEIGHT: Double = 0.0" in src
    assert "val HMM_EMISSIONS: EmissionTable = EmissionTable.PHYSIOLOGY" in src
    assert "0.060 vs 0.080" in src and "Gaussian(" not in src
    assert max(len(line) for line in src.splitlines()) <= 140


def test_trained_hmm_values_are_written_exactly():
    em = {s: {d: {"mean": g["mean"] + 0.123456789012, "sd": g["sd"] * 1.5} for d, g in v.items()}
          for s, v in PHYSIOLOGY_EMISSIONS.items()}
    hmm = {"emissions": em, "meanBouts": {k: v + 0.25 for k, v in DEFAULT_MEAN_BOUTS.items()},
           "transitions": dict(DEFAULT_TRANSITIONS)}
    sel = dict(SELECTION, hmm={"table": 0.08, "trained": 0.09, "trainedPool": "walch+bidsleep", "useTrained": True})
    src = render({"estimator": "HMM", "hybrid": HYBRID, "hmm": hmm}, sel, "r2", "2026-10-13", "Walch + BIDSleep")
    assert "EmissionTable.PHYSIOLOGY" in src                      # mentioned as the fallback that stays available
    assert "val HMM_EMISSIONS: EmissionTable =" in src and "val ESTIMATOR: EstimatorType = EstimatorType.HMM" in src
    mean = em["deep"]["hrNorm"]["mean"]
    assert f"hrNorm = Gaussian(mean = {mean!r}, sd = {em['deep']['hrNorm']['sd']!r})" in src
    # the argument names are the Kotlin constructor parameters of AlgoParams.kt
    assert set(re.findall(r"^\s+(\w+Min) = ", src, re.M)) == set(data_class_fields("MeanBouts"))
    assert set(re.findall(r"^\s+(\w+To\w+) = ", src, re.M)) == set(data_class_fields("TransitionWeights"))
    assert set(re.findall(r"^\s+(\w+) =$", src, re.M)) == set(data_class_fields("EmissionTable"))
    assert set(re.findall(r"(hr\w+) = Gaussian", src)) == set(data_class_fields("StateEmission"))


