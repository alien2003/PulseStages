import re

import pytest

import train
from kotlin_contract import data_class_fields
from pulsetrain import kotlin_defaults
from pulsetrain.kotlin_defaults import DefaultsError, render
from pulsetrain.stats import DEFAULT_MEAN_BOUTS, DEFAULT_TRANSITIONS, PHYSIOLOGY_EMISSIONS
from pulsetrain.util import write_json

SELECTION = {
    "estimatorScores": {"RULES": 0.07, "HMM": 0.08, "HYBRID": 0.29},
    "classifier": {"chosen": "lr", "config": "walch"},
    "decoderParams": {"params": {}, "count": 40, "folds": 62},
    "hmm": {"table": 0.08, "trained": 0.06, "trainedPool": "walch", "useTrained": False},
}
HYBRID = {"durationModel": "GEOMETRIC", "emissionWeight": 0.7, "timePriorWeight": 0.0}


def test_physiology_table_kept_when_trained_hmm_loses():
    src = render({"estimator": "HYBRID", "hybrid": HYBRID}, SELECTION, "r1", "2026-10-13T00:00:00Z", "Walch 1.0.0")
    head = src.splitlines()[:2]
    assert head[0] == "// Generated by tools/train/train.py defaults --run r1 from"
    assert head[1] == "// Walch 1.0.0, 2026-10-13; do not edit by hand."
    assert "`mise exec -- python -I tools/train/train.py defaults --run <run> --write`" in src   # not wrapped
    assert "val ESTIMATOR: EstimatorType = EstimatorType.HYBRID" in src
    assert "val HYBRID_DURATION_MODEL: DurationModel = DurationModel.GEOMETRIC" in src
    assert "const val HYBRID_EMISSION_WEIGHT: Double = 0.7" in src
    assert "const val HYBRID_TIME_PRIOR_WEIGHT: Double = 0.0" in src
    assert "val HMM_EMISSIONS: EmissionTable = EmissionTable.PHYSIOLOGY" in src
    assert "0.060 vs 0.080" in src and "Gaussian(" not in src
    assert max(len(line) for line in src.splitlines()) <= 140


def test_trained_hmm_values_are_written_exactly():
    em = {s: {d: {"mean": g["mean"] + 0.123456789012, "sd": g["sd"] * 1.5} for d, g in v.items()}
          for s, v in PHYSIOLOGY_EMISSIONS.items()}
    hmm = {"emissions": em, "meanBouts": {k: v + 0.25 for k, v in DEFAULT_MEAN_BOUTS.items()},
           "transitions": dict(DEFAULT_TRANSITIONS)}
    sel = dict(SELECTION, hmm={"table": 0.08, "trained": 0.09, "trainedPool": "walch+bidsleep", "useTrained": True})
    src = render({"estimator": "HMM", "hybrid": HYBRID, "hmm": hmm}, sel, "r2", "2026-10-13", "Walch + BIDSleep")
    assert "EmissionTable.PHYSIOLOGY" in src                      # mentioned as the fallback that stays available
    assert "val HMM_EMISSIONS: EmissionTable =" in src and "val ESTIMATOR: EstimatorType = EstimatorType.HMM" in src
    mean = em["deep"]["hrNorm"]["mean"]
    assert f"hrNorm = Gaussian(mean = {mean!r}, sd = {em['deep']['hrNorm']['sd']!r})" in src
    # the argument names are the Kotlin constructor parameters of AlgoParams.kt
    assert set(re.findall(r"^\s+(\w+Min) = ", src, re.M)) == set(data_class_fields("MeanBouts"))
    assert set(re.findall(r"^\s+(\w+To\w+) = ", src, re.M)) == set(data_class_fields("TransitionWeights"))
    assert set(re.findall(r"^\s+(\w+) =$", src, re.M)) == set(data_class_fields("EmissionTable"))
    assert set(re.findall(r"(hr\w+) = Gaussian", src)) == set(data_class_fields("StateEmission"))


@pytest.mark.parametrize("defaults,msg", [
    ({"estimator": "HSMM", "hybrid": HYBRID}, "estimator"),
    ({"estimator": "HYBRID", "hybrid": {"durationModel": "EXPLICIT"}}, "emissionWeight"),
    ({"estimator": "HYBRID", "hybrid": dict(HYBRID, emissionWeight=float("nan"))}, "finite"),
    ({"estimator": "HYBRID", "hybrid": dict(HYBRID, durationModel="SEMI")}, "durationModel"),
    ({"estimator": "HYBRID", "hybrid": HYBRID, "hmm": {}}, "disagree"),
])
def test_invalid_defaults(defaults, msg):
    with pytest.raises(DefaultsError, match=msg):
        render(defaults, SELECTION, "r", "2026", "x")


def test_cli_renders_a_run(tmp_path, capsys):
    run = tmp_path / "out" / "r3"
    write_json(run / "trained_defaults.json", {"estimator": "HYBRID", "hybrid": HYBRID})
    write_json(run / "summary.json", {"meta": {"run": "r3", "createdAt": "2026-10-13T01:02:03Z"},
                                      "selection": SELECTION})
    assert train.main(["defaults", "--run", "r3", "--out-root", str(tmp_path / "out")]) == 0
    assert "--run r3" in capsys.readouterr().out
    target = tmp_path / "TrainedDefaults.kt"
    assert train.main(["defaults", "--run", "r3", "--out-root", str(tmp_path / "out"), "--output", str(target)]) == 0
    assert target.read_text().startswith("// Generated by tools/train/train.py defaults --run r3")
    assert kotlin_defaults.KOTLIN_PATH.name == "TrainedDefaults.kt"


def test_time_prior_is_always_generated():
    from pulsetrain.stats import SPEC_TIME_PRIOR, TIME_PRIOR_KEYS

    src = render({"estimator": "HYBRID", "hybrid": HYBRID}, SELECTION, "r1", "2026-10-13", "Walch")
    assert "val HMM_TIME_PRIOR: HmmTimePrior = HmmTimePrior()" in src
    hmm = {"emissions": PHYSIOLOGY_EMISSIONS, "meanBouts": DEFAULT_MEAN_BOUTS, "transitions": DEFAULT_TRANSITIONS}
    sel = dict(SELECTION, hmm={"table": 0.08, "trained": 0.09, "trainedPool": "walch", "useTrained": True})
    old = render({"estimator": "HMM", "hybrid": HYBRID, "hmm": hmm}, sel, "r", "2026", "x")   # runs before the
    assert "val HMM_TIME_PRIOR: HmmTimePrior = HmmTimePrior()" in old and "not estimated" in old   # time prior
    tp = {k: v * 1.1 + 0.0123 for k, v in SPEC_TIME_PRIOR.items()}
    new = render({"estimator": "HMM", "hybrid": HYBRID, "hmm": {**hmm, **tp}}, sel, "r", "2026", "x")
    assert "val HMM_TIME_PRIOR: HmmTimePrior =" in new and "HmmTimePrior()" not in new
    assert set(re.findall(r"^\s+(\w+) = [-\d.e]+,$", new.split("HMM_TIME_PRIOR")[1], re.M)) == set(
        data_class_fields("HmmTimePrior")) == set(TIME_PRIOR_KEYS)
    assert f"deepTimeSlope = {tp['deepTimeSlope']!r}," in new
    with pytest.raises(DefaultsError, match="incomplete"):
        render({"estimator": "HMM", "hybrid": HYBRID, "hmm": {**hmm, "deepTimeSlope": 1.0}}, sel, "r", "2026", "x")


def test_gate_rejection_is_explained():
    sel = dict(SELECTION, hmm={"table": 0.07, "trained": 0.11, "trainedPool": "walch+bidsleep", "betterKappa": True,
                               "useTrained": False, "validity": {"valid": False, "problems": [
                                   "hrNorm means violate DEEP < LIGHT < REM < AWAKE"]}},
               decoderParams={"params": {}, "count": 78, "folds": 156, "selections": 5, "selectionsTotal": 10})
    src = render({"estimator": "HYBRID", "hybrid": HYBRID}, sel, "r", "2026", "x")
    flat = " ".join(line.strip(" */") for line in src.splitlines())
    assert "failed the validity gate (hrNorm means violate DEEP < LIGHT < REM < AWAKE)" in flat
    assert "5 of 10 distinct inner selections, 78 of 156 outer folds" in flat
    assert "val HMM_EMISSIONS: EmissionTable = EmissionTable.PHYSIOLOGY" in src
